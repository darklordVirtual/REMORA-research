"""Generate the OT pilot's credentials on first start (SR-06).

Writes deploy/ot-pilot/.env (mode 600) with random tokens for the agent,
approver, supervisor and viewer roles, and random signing keys for PDP
tokens, leases, the audit chain and envelopes. docker compose reads that file
automatically; the compose file refuses to start without it, so a pilot no
longer boots with fixed literal tokens or keys anyone can guess. The keys
used to be literals in docker-compose.yml, and anyone holding the lease key
could sign a lease for any call (RMR-SEC-0001).

A .env written before the keys existed has none; rotate with --force.

    python deploy/ot-pilot/init_tokens.py          # create once
    python deploy/ot-pilot/init_tokens.py --force  # rotate (existing runs and
                                                   # issued grants die with
                                                   # the old tokens)

The console never reads the write-capable tokens from here; the operator
enters them per request in the UI.
"""
from __future__ import annotations

import os
import secrets
import sys
import tempfile
from pathlib import Path

ENV_PATH = Path(__file__).resolve().parent / ".env"


def main() -> int:
    force = "--force" in sys.argv[1:]
    if ENV_PATH.exists() and not force:
        print(f"{ENV_PATH} already exists; use --force to rotate the tokens.",
              file=sys.stderr)
        return 1

    tokens = {name: f"ot-{secrets.token_urlsafe(24)}" for name in
              ("AGENT", "APPROVER", "SUPERVISOR", "VIEWER")}
    # 32 random bytes each, hex: the production startup check refuses keys
    # under 32 bytes or with a placeholder shape.
    keys = {name: secrets.token_hex(32) for name in
            ("PDP", "LEASE", "AUDIT", "ENVELOPE")}
    content = "\n".join(
        [
            "# Generated by deploy/ot-pilot/init_tokens.py — do not commit.",
            f"OT_TOKEN_AGENT={tokens['AGENT']}",
            f"OT_TOKEN_APPROVER={tokens['APPROVER']}",
            f"OT_TOKEN_SUPERVISOR={tokens['SUPERVISOR']}",
            f"OT_TOKEN_VIEWER={tokens['VIEWER']}",
            f"OT_PDP_SIGNING_KEY={keys['PDP']}",
            f"OT_LEASE_SIGNING_KEY={keys['LEASE']}",
            f"OT_AUDIT_SIGNING_KEY={keys['AUDIT']}",
            f"OT_ENVELOPE_SIGNING_KEY={keys['ENVELOPE']}",
            "",
        ]
    )
    # mkstemp creates mode 600 before any credential is written. Publish the
    # complete file atomically; rotation replaces symlinks rather than writing
    # through them, and first-start publication cannot clobber another run.
    fd, temporary = tempfile.mkstemp(prefix=".env-", dir=ENV_PATH.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(content)
        if force:
            os.replace(temporary, ENV_PATH)
        else:
            try:
                os.link(temporary, ENV_PATH)
            except FileExistsError:
                print(f"{ENV_PATH} already exists; use --force to rotate the tokens.",
                      file=sys.stderr)
                return 1
    finally:
        Path(temporary).unlink(missing_ok=True)
    print(f"wrote {ENV_PATH} (mode 600). The agent/approver tokens are entered "
          "per request in the console UI; the viewer token is read by the "
          "console for its dashboard polls.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
