"""Generate the OT pilot's credentials on first start (SR-06).

Writes deploy/ot-pilot/.env (mode 600) with random tokens for the agent,
approver, supervisor and viewer roles. docker compose reads that file
automatically; the compose file refuses to start without it, so a pilot no
longer boots with fixed literal tokens anyone can guess.

    python deploy/ot-pilot/init_tokens.py          # create once
    python deploy/ot-pilot/init_tokens.py --force  # rotate (existing runs and
                                                   # issued grants die with
                                                   # the old tokens)

The console never reads the write-capable tokens from here; the operator
enters them per request in the UI.
"""
from __future__ import annotations

import os
import secrets
import sys
from pathlib import Path

ENV_PATH = Path(__file__).resolve().parent / ".env"


def main() -> int:
    force = "--force" in sys.argv[1:]
    if ENV_PATH.exists() and not force:
        print(f"{ENV_PATH} already exists; use --force to rotate the tokens.",
              file=sys.stderr)
        return 1

    tokens = {name: f"ot-{secrets.token_urlsafe(24)}" for name in
              ("AGENT", "APPROVER", "SUPERVISOR", "VIEWER")}
    content = "\n".join(
        [
            "# Generated by deploy/ot-pilot/init_tokens.py — do not commit.",
            f"OT_TOKEN_AGENT={tokens['AGENT']}",
            f"OT_TOKEN_APPROVER={tokens['APPROVER']}",
            f"OT_TOKEN_SUPERVISOR={tokens['SUPERVISOR']}",
            f"OT_TOKEN_VIEWER={tokens['VIEWER']}",
            "",
        ]
    )
    ENV_PATH.write_text(content, encoding="utf-8")
    os.chmod(ENV_PATH, 0o600)
    print(f"wrote {ENV_PATH} (mode 600). The agent/approver tokens are entered "
          "per request in the console UI; the viewer token is read by the "
          "console for its dashboard polls.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
