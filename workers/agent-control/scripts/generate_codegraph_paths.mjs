#!/usr/bin/env node
// Regenerate src/codegraph.paths.ts from the files git tracks at HEAD.
//
//   node scripts/generate_codegraph_paths.mjs          # rewrite the file
//   node scripts/generate_codegraph_paths.mjs --check  # exit 1 if it is stale
//
// The keyword ranker serves this list, so a hand-maintained copy drifts:
// it kept deleted files and missed most new ones.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, "..", "src", "codegraph.paths.ts");
const repo = execFileSync("git", ["-C", here, "rev-parse", "--show-toplevel"], { encoding: "utf8" }).trim();

// Mirrors CODEGRAPH_SCOPE.exclude in src/codegraph.ts. None of these should
// be tracked, but the filter keeps an accidental commit out of the catalog.
const EXCLUDED = [/^\.git\//, /(^|\/)node_modules\//, /(^|\/)\.pytest_cache\//, /(^|\/)__pycache__\//, /^\.remora_session\//];

const paths = execFileSync("git", ["-C", repo, "ls-files", "-z"], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 })
  .split("\0")
  .filter(Boolean)
  .filter((path) => !EXCLUDED.some((pattern) => pattern.test(path)))
  .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

const body = [
  "// Generated by scripts/generate_codegraph_paths.mjs from `git ls-files`. Do not edit by hand.",
  "export const CODEGRAPH_PATHS = [",
  ...paths.map((path) => `  ${JSON.stringify(path)},`),
  "] as const;",
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const current = readFileSync(target, "utf8");
  if (current !== body) {
    console.error(`${target} is stale; run: node scripts/generate_codegraph_paths.mjs`);
    process.exit(1);
  }
  console.log(`codegraph.paths.ts is current (${paths.length} paths)`);
} else {
  writeFileSync(target, body);
  console.log(`wrote ${paths.length} paths to ${target}`);
}
